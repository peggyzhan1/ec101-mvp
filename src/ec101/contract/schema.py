@dataclass(frozen=True)
class Issue:
    sheet: str
    row: int | None
    column: str | None
    code: str
    message: str


def _empty(value: Any) -> bool:
    return value is None or (isinstance(value, str) and not value.strip())


def validate_rows(sheet: str, rows: Sequence[Mapping[str, Any]]) -> list[Issue]:
    if sheet not in SHEET_COLUMNS:
        return [Issue(sheet, None, None, "UNKNOWN_SHEET", f"未知工作表：{sheet}")]

    expected = set(SHEET_COLUMNS[sheet])
    required = REQUIRED_COLUMNS[sheet]
    issues: list[Issue] = []
    for row_number, row in enumerate(rows, start=2):
        for column in row:
            if column not in expected:
                issues.append(Issue(
                    sheet, row_number, column, "UNKNOWN_COLUMN",
                    f"{sheet} 第 {row_number} 行包含未知字段：{column}",
                ))
        for column in required:
            if _empty(row.get(column)):
                issues.append(Issue(
                    sheet, row_number, column, "REQUIRED_VALUE",
                    f"{sheet} 第 {row_number} 行必填字段为空：{column}",
                ))
    return issues
